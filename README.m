# Minimax Algorithm and Alpha-Beta Pruning

## Project Description
This project implements the Minimax Algorithm and Alpha-Beta Pruning Algorithm using Python. The program evaluates a binary game tree and determines the optimal value.

## Features
- Implementation of Minimax Algorithm
- Implementation of Alpha-Beta Pruning
- Comparison of nodes evaluated by both algorithms
- Counting of pruned nodes
- Calculation of efficiency improvement

## Algorithms Used
1. Minimax Algorithm
2. Alpha-Beta Pruning Algorithm


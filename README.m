Python

## How to Run
Run the following command:

python main.py

## Output
The program displays:
- Generated leaf node values
- Minimax nodes evaluated
- Optimal value
- Alpha-Beta Pruning nodes evaluated
- Number of pruned nodes
- Efficiency improvement
